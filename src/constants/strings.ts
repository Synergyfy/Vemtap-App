import type { LoyaltyRule, LoyaltyRuleFieldKey } from '@api/loyaltyApi';

/**
 * The seven numbers the single `loyalty_rules` row holds — the slice of
 * `LoyaltyRule` a rule card formats its value and footnote from. Type-only so
 * `strings.ts` keeps zero runtime imports (it is loaded by `api/client`, so a
 * real import here would close a cycle).
 */
export type LoyaltyRuleValues = Pick<LoyaltyRule, LoyaltyRuleFieldKey>;

/**
 * One rule card's copy: labels plus the formatters that turn the live row into
 * the value and footnote the card shows. `value`/`footnote` take the whole
 * slice so a card only interpolates the fields it actually owns.
 */
export interface LoyaltyRuleCardCopy {
  icon: string;
  title: string;
  tag: string;
  value: (rule: LoyaltyRuleValues) => string;
  footnote: (rule: LoyaltyRuleValues) => string;
  footnoteIcon: string;
  fields: LoyaltyRuleFieldKey[];
}

